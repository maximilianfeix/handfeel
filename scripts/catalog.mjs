// Counts how often each rule fires across the unchanged generated apps in evals/apps/*/before
// and writes docs/slop-catalog.md. Re-run after adding apps: node scripts/catalog.mjs
import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { scan, ruleCatalog } from '../dist/src/index.js';
import { parseCssColor, parseArgbInt, hex6, isAiPurple, DEFAULT_AI_ACCENTS } from '../dist/src/color.js';

const apps = readdirSync('evals/apps').filter((a) => existsSync(join('evals/apps', a, 'before'))).sort();
const per = new Map();
const purples = new Map();
const meta = [];
for (const a of apps) {
  const r = scan(join('evals/apps', a, 'before'));
  const prompt = readFileSync(join('evals/apps', a, 'PROMPT.md'), 'utf8');
  meta.push({ a, platform: r.platforms.join(', '), score: r.score, gen: /Generated \S+ by (.+?), in an empty/.exec(prompt)?.[1] ?? '' });
  const counts = new Map();
  for (const f of r.findings) counts.set(f.rule, (counts.get(f.rule) ?? 0) + 1);
  for (const [rule, n] of counts) {
    const cur = per.get(rule) ?? { apps: [], findings: 0 };
    cur.apps.push(a);
    cur.findings += n;
    per.set(rule, cur);
  }
  // every literal color in the indigo/violet band, per app
  for (const f of walk(join('evals/apps', a, 'before'))) {
    const src = readFileSync(f, 'utf8');
    const hits = [...src.matchAll(/#[0-9a-fA-F]{6}\b/g)].map((m) => parseCssColor(m[0])).concat([...src.matchAll(/0x[0-9a-fA-F]{8}\b/g)].map((m) => parseArgbInt(m[0])));
    for (const c of hits) if (c && isAiPurple(c)) {
      const k = hex6(c);
      const s = purples.get(k) ?? new Set();
      s.add(a);
      purples.set(k, s);
    }
  }
}
function walk(d) {
  return readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : /\.(tsx?|dart|swift|kt)$/.test(e.name) ? [join(d, e.name)] : []));
}
const titles = Object.fromEntries(ruleCatalog().map((r) => [r.id, r.title]));
const appsWithPurple = new Set([...purples.values()].flatMap((s) => [...s]));
const rows = [...per.entries()].sort((x, y) => y[1].apps.length - x[1].apps.length || y[1].findings - x[1].findings);
let md = `# Slop catalog

What the scanner finds in apps that were generated from plain prompts and committed unchanged. This is the measurement behind the rules that have no official platform source (emoji icons, default purple, gradients, glass). Regenerate with \`node scripts/catalog.mjs\`.

Sample: ${apps.length} apps generated on 2026-11-12. Prompts and generator models are in \`evals/apps/<app>/PROMPT.md\`. The sample is small and the prompts asked for "modern", "beautiful", "premium" or "polished" apps, which is how people ask. Treat the shares as a description of this sample, not of all generated apps.

| App | Platform | Generated by | Score |
|---|---|---|---:|
${meta.map((m) => `| ${m.a} | ${m.platform} | ${m.gen} | ${m.score} |`).join('\n')}

## How often each rule fires

| Rule | Apps | Findings |
|---|---:|---:|
${rows.map(([id, v]) => `| \`${id}\` ${titles[id] ? '(' + titles[id] + ')' : ''} | ${v.apps.length} of ${apps.length} | ${v.findings} |`).join('\n')}

## The purple

${appsWithPurple.size} of ${apps.length} apps contain at least one color in the indigo-violet band (hue 235-295°, saturation ≥ 40 %, lightness 30-80 %), none of them asked for. By generator: ${[...new Set(meta.map((m) => m.gen))].map((g) => `${meta.filter((m) => m.gen === g && appsWithPurple.has(m.a)).length} of ${meta.filter((m) => m.gen === g).length} apps by ${g}`).join('; ')}. With ${apps.length} apps this is an observation, not a rate. The colors found:

| Color | Apps | Stock accent list |
|---|---|---|
${[...purples.entries()].sort().map(([k, s]) => `| \`${k}\` | ${[...s].join(', ')} | ${DEFAULT_AI_ACCENTS.has(k) ? 'yes' : ''} |`).join('\n')}

The stock accent list (\`default-ai-accent\`) only matches exact values: the Tailwind indigo, violet and purple 400-600 steps, #667EEA / #764BA2, #6C63FF, #6C5CE7 and #7F5AF0. The \`purple-gradient\` rule uses the hue band instead, but only inside gradients.
`;
writeFileSync('docs/slop-catalog.md', md);
